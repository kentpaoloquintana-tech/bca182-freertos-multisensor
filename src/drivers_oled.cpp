inline void SCL(bool high)
{
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, high ? GPIO_PIN_SET : GPIO_PIN_RESET);
    __NOP();
    __NOP();
}

inline void SDA(bool high)
{
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_7, high ? GPIO_PIN_SET : GPIO_PIN_RESET);
    __NOP();
    __NOP();
}

void I2C_Start(void)
{
    SDA(true);
    SCL(true);
    SDA(false);
    SCL(false);
}

void I2C_Stop(void)
{
    SDA(false);
    SCL(true);
    SDA(true);
}

void I2C_WriteByte(uint8_t value)
{
    for (uint8_t bit = 0; bit < 8; ++bit) {
        SDA((value & 0x80U) != 0U);
        value <<= 1U;
        SCL(true);
        SCL(false);
    }
    SDA(true);
    SCL(true);
    SCL(false);
}

void OLED_WriteCommands(const uint8_t *commands, uint8_t count)
{
    I2C_Start();
    I2C_WriteByte(static_cast<uint8_t>(kOledAddress << 1U));
    I2C_WriteByte(0x00);
    for (uint8_t i = 0; i < count; ++i) {
        I2C_WriteByte(commands[i]);
    }
    I2C_Stop();
}

void OLED_WriteData(const uint8_t *data, uint8_t count)
{
    I2C_Start();
    I2C_WriteByte(static_cast<uint8_t>(kOledAddress << 1U));
    I2C_WriteByte(0x40);
    for (uint8_t i = 0; i < count; ++i) {
        I2C_WriteByte(data[i]);
    }
    I2C_Stop();
}

void AppendText(char *out, int &index, const char *text)
{
    while (*text != '\0') {
        out[index++] = *text++;
    }
}

