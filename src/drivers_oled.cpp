void OLED_Init(void)
{
    __HAL_RCC_GPIOB_CLK_ENABLE();
    GPIO_InitTypeDef gpio = {};
    gpio.Pin = GPIO_PIN_6 | GPIO_PIN_7;
    gpio.Mode = GPIO_MODE_OUTPUT_OD;
    gpio.Pull = GPIO_PULLUP;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &gpio);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6 | GPIO_PIN_7, GPIO_PIN_SET);

    const uint8_t initSequence[] = {
        0xAE, 0x20, 0x02, 0xB0, 0xC8, 0x00, 0x10, 0x40, 0x81, 0xFF,
        0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3, 0x00, 0xD5, 0xF0, 0xD9,
        0x22, 0xDA, 0x12, 0xDB, 0x20, 0x8D, 0x14, 0xAF
    };
    OLED_WriteCommands(initSequence, sizeof(initSequence));
    OLED_Clear();
    OLED_Update();
}

void OLED_SetDisplay(bool enabled)
{
    const uint8_t command = enabled ? 0xAFU : 0xAEU;
    OLED_WriteCommands(&command, 1U);
}

void OLED_Clear(void)
{
    memset(oledBuffer, 0, sizeof(oledBuffer));
}

void OLED_DrawString(uint8_t x, uint8_t page, const char *text)
{
    if (page >= 8U || text == NULL) {
        return;
    }
    while (*text != '\0' && x <= 122U) {
        char character = *text++;
        if (character >= 'a' && character <= 'z') {
            character = static_cast<char>(character - 'a' + 'A');
        }
        const uint8_t *glyph;
        if (character >= ' ' && character <= 'Z') {
            glyph = font5x7[character - ' '];
        } else if (character >= '[' && character <= '`') {
            glyph = fontBracketSymbols[character - '['];
        } else if (character >= '{' && character <= '~') {
            glyph = fontBraceSymbols[character - '{'];
        } else {
            glyph = font5x7[0];
        }
        for (uint8_t column = 0; column < 5U; ++column) {
            oledBuffer[page * 128U + x + column] = glyph[column];
        }
        oledBuffer[page * 128U + x + 5U] = 0;
        x += 6U;
    }
}

void OLED_Update(void)
{
    for (uint8_t page = 0; page < 8U; ++page) {
        const uint8_t pageCommands[] = {
            static_cast<uint8_t>(0xB0U + page), 0x00, 0x10
        };
        OLED_WriteCommands(pageCommands, sizeof(pageCommands));
        OLED_WriteData(&oledBuffer[page * 128U], 128);
    }
}

void Format_Fixed1(char *out, const char *prefix, float value, const char *suffix)
{
    int index = 0;
    AppendText(out, index, prefix);
    if (value < 0.0f) {
        out[index++] = '-';
        value = -value;
    }
    const int tenths = static_cast<int>(value * 10.0f + 0.5f);
    const int whole = tenths / 10;
    if (whole >= 100) {
        out[index++] = static_cast<char>('0' + (whole / 100) % 10);
    }
    if (whole >= 10) {
        out[index++] = static_cast<char>('0' + (whole / 10) % 10);
    }
    out[index++] = static_cast<char>('0' + whole % 10);
    out[index++] = '.';
    out[index++] = static_cast<char>('0' + tenths % 10);
    AppendText(out, index, suffix);
    out[index] = '\0';
}

void Format_Int(char *out, const char *prefix, int value, const char *suffix)
{
    int index = 0;
    AppendText(out, index, prefix);
    if (value < 0) {
        out[index++] = '-';
        value = -value;
    }
    if (value >= 100) {
        out[index++] = static_cast<char>('0' + (value / 100) % 10);
    }
    if (value >= 10) {
        out[index++] = static_cast<char>('0' + (value / 10) % 10);
    }
    out[index++] = static_cast<char>('0' + value % 10);
    AppendText(out, index, suffix);
    out[index] = '\0';
}
